    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String query = jTextField1.getText().trim();
        if (query.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter ID or Name to search.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        DefaultTableModel model = StudentManager.tableModel;
        boolean found = false;

        for (int i = 0; i < model.getRowCount(); i++) {
            String id = model.getValueAt(i, 0).toString().toLowerCase();
            String name = model.getValueAt(i, 1).toString().toLowerCase();

            if (id.equals(query) || name.contains(query)) {
                resultTable.setRowSelectionInterval(i, i);
                resultTable.scrollRectToVisible(resultTable.getCellRect(i, 0, true));
                found = true;
                break;
            }
        }

        if (!found) {
            JOptionPane.showMessageDialog(this, "No matching student found.", "Info", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int selectedRow = resultTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a student to update.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {

            String currentAge = resultTable.getValueAt(selectedRow, 2).toString();
            String currentDept = resultTable.getValueAt(selectedRow, 4).toString();
            String currentGpa = resultTable.getValueAt(selectedRow, 5).toString();

            String ageInput = JOptionPane.showInputDialog("Enter new Age:", currentAge);
            String deptInput = JOptionPane.showInputDialog("Enter new Department:", currentDept);
            String gpaInput = JOptionPane.showInputDialog("Enter new GPA:", currentGpa);

            if (ageInput == null || deptInput == null || gpaInput == null) {
                JOptionPane.showMessageDialog(this, "Update cancelled.", "Info", JOptionPane.INFORMATION_MESSAGE);
                return;
            }

            int newAge = Integer.parseInt(ageInput.trim());
            float newGpa = Float.parseFloat(gpaInput.trim());

            if (newAge <= 0) {
                JOptionPane.showMessageDialog(this, "Age must be a positive number.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (newGpa < 0 || newGpa > 4) {
                JOptionPane.showMessageDialog(this, "GPA must be between 0 and 4.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            String newDept = deptInput.trim();
            if (newDept.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Department cannot be empty.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            int id = Integer.parseInt(jTextField1.getText().trim());

//            StudentDatabase sdb = new StudentDatabase("students.txt");
            AuthenticationManager auth = new AuthenticationManager();
//            sdb.readFromFile();
            AdminRole admin = new AdminRole(auth);

            boolean success = admin.updateStudent(id, newAge, newDept, newGpa);

            if (success) {
                JOptionPane.showMessageDialog(this, "Student updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Update failed. Check inputs or student ID.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for Age and GPA.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton2ActionPerformed

